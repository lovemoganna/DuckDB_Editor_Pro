async (page) => {
  const title='DuckDB 函数目录 · 透视验证';
  await page.getByRole('button',{name:`更多组件选项 ${title}`,exact:true}).click();
  await page.getByRole('button',{name:'全屏查看',exact:true}).click();
  await page.getByRole('button',{name:'关闭全屏透视',exact:true}).waitFor();
  await page.screenshot({path:'docs/pivot-experience-20261014/fullscreen.png',fullPage:true});
  await page.getByRole('button',{name:'关闭全屏透视',exact:true}).click();
  await page.getByRole('button',{name:`更多组件选项 ${title}`,exact:true}).click();
  await page.getByRole('button',{name:'编辑透视表',exact:true}).click();
  await page.getByTestId('pivot-editor').waitFor({timeout:30000});
  if(await page.getByLabel('列',{exact:true}).inputValue()!=='return_type')throw new Error('Column configuration not restored');
  if(await page.getByLabel('值 2 聚合方式',{exact:true}).inputValue()!=='avg')throw new Error('Aggregation not restored');
  if(await page.getByLabel('当前展示的值',{exact:true}).inputValue()!=='1')throw new Error('Visible metric not restored');
  await page.getByRole('button',{name:'添加筛选',exact:true}).click();
  await page.getByLabel('筛选 1 字段',{exact:true}).selectOption('parameter_count');
  await page.getByLabel('筛选 1 条件',{exact:true}).selectOption('>=');
  await page.getByLabel('筛选 1 值',{exact:true}).fill('2');
  await page.getByLabel('分析名称',{exact:true}).fill(`${title} · 已更新`);
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='保存分析')?.disabled,null,{timeout:30000});
  await page.getByRole('button',{name:'保存分析',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor({timeout:30000});
  await page.setViewportSize({width:768,height:900});
  await page.screenshot({path:'docs/pivot-experience-20261014/editor-narrow-configuration.png',fullPage:true});
  await page.getByRole('button',{name:'收起配置',exact:true}).click();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Narrow screen has page-level horizontal overflow');
  await page.screenshot({path:'docs/pivot-experience-20261014/editor-narrow.png',fullPage:true});
  await page.setViewportSize({width:1366,height:900});
  await page.getByRole('button',{name:'仪表盘',exact:true}).click();
  await page.getByText(`${title} · 已更新`,{exact:true}).first().waitFor({timeout:30000});
  await page.getByText('1 项分析组件',{exact:true}).waitFor();
  await page.reload();
  await page.getByText(`${title} · 已更新`,{exact:true}).first().waitFor({timeout:30000});
  await page.getByRole('button',{name:`更多组件选项 ${title} · 已更新`,exact:true}).click();
  await page.getByRole('button',{name:'编辑透视表',exact:true}).click();
  await page.getByTestId('pivot-editor').waitFor({timeout:30000});
  if(await page.getByLabel('筛选 1 值',{exact:true}).inputValue()!=='2')throw new Error('Filter was lost after browser reload');
  if(await page.getByLabel('值 2 聚合方式',{exact:true}).inputValue()!=='avg')throw new Error('Saved aggregation was lost after reload');
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='保存分析')?.disabled,null,{timeout:30000});
  await page.screenshot({path:'docs/pivot-experience-20261014/restored-after-reload.png',fullPage:true});
}
