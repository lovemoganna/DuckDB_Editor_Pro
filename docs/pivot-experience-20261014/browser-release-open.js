async (page) => {
  await page.setViewportSize({width:1366,height:900});
  await page.addInitScript(()=>localStorage.setItem('duckdb-active-catalog','duckdb_manager_workspace'));
  await page.reload();
  await page.getByRole('tab',{name:'SQL',exact:true}).waitFor({timeout:30000});
  await page.getByRole('tab',{name:'SQL',exact:true}).click();
  await page.getByRole('textbox').nth(1).fill("SELECT function_type, return_type, len(parameters) AS parameter_count FROM duckdb_functions() WHERE function_type IN ('scalar', 'aggregate')");
  await page.getByRole('button',{name:'运行',exact:true}).click();
  await page.getByRole('button',{name:'透视分析',exact:true}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'透视分析',exact:true}).click();
  await page.getByTestId('pivot-editor').waitFor({timeout:30000});
  const ready=()=>page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='保存分析')?.disabled,null,{timeout:30000});
  await ready();
  await page.getByLabel('列',{exact:true}).selectOption('return_type');await ready();
  const cell=page.getByRole('button',{name:'查看明细 aggregate / BIGINT',exact:true});
  await cell.click();
  await page.getByRole('dialog').getByText('1–50 条',{exact:true}).waitFor({timeout:30000});
  await page.getByRole('dialog').getByRole('button',{name:'下一页',exact:true}).click();
  await page.getByRole('dialog').getByText('51–84 条',{exact:true}).waitFor({timeout:30000});
  await page.screenshot({path:'docs/pivot-experience-20261014/details.png',fullPage:true});
  await page.keyboard.press('Escape');
  if(!await cell.evaluate(element=>element===document.activeElement))throw new Error('Focus was not restored');
  await page.getByRole('button',{name:'交换行列',exact:true}).click();
  if(await page.getByLabel('行',{exact:true}).inputValue()!=='return_type')throw new Error('Row/column exchange failed');
  await page.getByRole('button',{name:'交换行列',exact:true}).click();
  await page.getByRole('button',{name:'添加值',exact:true}).click();
  await page.getByLabel('值 2 字段',{exact:true}).selectOption('parameter_count');
  await page.getByLabel('值 2 聚合方式',{exact:true}).selectOption('avg');
  await page.getByLabel('值 2 名称',{exact:true}).fill('平均参数数');
  await page.getByLabel('当前展示的值',{exact:true}).selectOption('1');
  await page.getByLabel('分析名称',{exact:true}).fill('DuckDB 函数目录 · 透视验证');await ready();
  await page.getByRole('button',{name:'保存并加入首页',exact:true}).click();
  await page.getByRole('button',{name:'另存为',exact:true}).waitFor({timeout:30000});
  await page.getByText('已保存',{exact:true}).waitFor({timeout:30000});
  await ready();
  await page.screenshot({path:'docs/pivot-experience-20261014/editor-wide.png',fullPage:true});
  await page.getByRole('button',{name:'仪表盘',exact:true}).click();
  await page.getByText('DuckDB 函数目录 · 透视验证',{exact:true}).first().waitFor({timeout:30000});
  await page.getByText('总计（全部符合条件的来源）',{exact:true}).waitFor({timeout:30000});
  await page.screenshot({path:'docs/pivot-experience-20261014/home-pivot.png',fullPage:true});
}
