import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';

export async function verifyVisualizationLibrary(page,output) {
  const checks=[];
  const pass=name=>{checks.push(name);console.log(`PASS ${name}`);};
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('navigation',{name:'业务领域大类'}).getByRole('button',{name:'分析洞察',exact:true}).click();
  await page.getByRole('tab',{name:'可视化',exact:true}).click();
  await page.getByRole('heading',{name:'可视化资产',exact:true}).waitFor({timeout:120000});
  await page.getByLabel('关联数据表筛选').selectOption('all');
  await page.locator('.viz-gallery-card h3').first().waitFor({timeout:120000});
  let title=await page.locator('.viz-gallery-card h3').first().innerText();
  const total=await page.locator('.viz-gallery-card').count();
  assert.ok(total>1,'expected actual assets');
  const capture=async name=>{
    await page.locator('.viz-library-content').evaluate(el=>{el.scrollTop=0;});
    await page.screenshot({path:path.join(output,`${name}.png`),animations:'disabled'});
  };
  for(const theme of ['dark','light']) {
    const toggle=page.getByRole('button',{name:theme==='light'?'切换为浅色模式':'切换为深色模式',exact:true});
    if(await toggle.count())await toggle.click();
    await page.getByRole('button',{name:'画廊',exact:true}).click();
    await capture(`viz-gallery-${theme}`);
    await page.getByRole('button',{name:'列表',exact:true}).click();
    await page.getByRole('list',{name:'图表资产列表'}).waitFor();
    await page.waitForFunction(()=>![...document.querySelectorAll('.viz-asset-result')].some(el=>el.textContent.includes('读取中')));
    assert.equal(await page.locator('.viz-asset-row').count(),total);
    assert.equal(await page.locator('.viz-library-content canvas').count(),0);
    for(const width of [1440,1024,768,390,375]) {
      await page.setViewportSize({width,height:1000});
      const bounds=await page.locator('.viz-asset-row').evaluateAll(es=>es.map(el=>el.getBoundingClientRect().toJSON()));
      assert.ok(bounds.every(rect=>rect.width>0&&rect.x>=0&&rect.right<=width+1),'asset row outside viewport');
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page horizontal overflow');
      assert.ok(await page.locator('.viz-library-header h1').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'library title is truncated');
      await capture(`viz-list-${theme}-${width}`);
    }
    const typeFilter=page.getByLabel('图表类型筛选');
    assert.equal(await typeFilter.isVisible(),false);
    const kpis=(await page.locator('.viz-asset-type').allTextContents()).filter(label=>label==='指标卡').length;
    await page.getByRole('button',{name:/^筛选/}).click();
    assert.equal(await typeFilter.isVisible(),true);
    await typeFilter.selectOption('kpi');
    assert.ok(kpis>0);assert.equal(await page.locator('.viz-asset-row').count(),kpis);
    await capture(`viz-mobile-filters-${theme}`);
    await typeFilter.selectOption('all');
    await page.getByRole('button',{name:/^筛选/}).click();
    assert.equal(await page.locator('.viz-asset-row').count(),total);
    await page.setViewportSize({width:1440,height:1000});
    pass(`${theme}: ${total} real assets, canvas-free list, five widths, mobile filter expansion and KPI selection`);
  }
  const barRow=page.locator('.viz-asset-row').filter({has:page.locator('.viz-asset-type').filter({hasText:'柱状图'})}).first();
  if(await barRow.count())title=await barRow.locator('.viz-asset-name > button').innerText();
  const search=page.getByPlaceholder('搜索图表名称、指标或 SQL...');
  await search.fill(title);
  assert.ok(await page.locator('.viz-asset-row').count()>0);
  await search.fill('no_matching_asset_quality_20261016');
  await page.getByRole('heading',{name:'未找到匹配的图表'}).waitFor();
  await capture('viz-no-results');
  await page.getByRole('button',{name:'重置所有筛选',exact:true}).click();
  assert.equal(await page.locator('.viz-asset-row').count(),total);
  pass('search and reset preserve the asset set and list presentation');
  const trigger=page.getByRole('button',{name:`查看图表 ${title}`,exact:true}).first();
  await trigger.click();
  const dialog=page.getByRole('dialog',{name:'专注查看',exact:true});
  await dialog.waitFor();
  await dialog.getByText(title,{exact:true}).first().waitFor();
  assert.ok(await dialog.evaluate(el=>el.contains(document.activeElement)));
  for(let i=0;i<12;i++)await page.keyboard.press('Tab');
  assert.ok(await dialog.evaluate(el=>el.contains(document.activeElement)));
  const pin=dialog.getByRole('button',{name:/^(取消)?固定到仪表盘$/});
  const initialPin=await pin.getAttribute('aria-pressed');
  await pin.click();
  await page.waitForFunction(expected=>[...document.querySelectorAll('[role="dialog"] button[aria-pressed]')].some(el=>el.getAttribute('aria-pressed')===expected),initialPin==='true'?'false':'true');
  await pin.click();
  await page.waitForFunction(expected=>[...document.querySelectorAll('[role="dialog"] button[aria-pressed]')].some(el=>el.getAttribute('aria-pressed')===expected),initialPin);
  const download=page.waitForEvent('download');
  await dialog.getByRole('button',{name:'下载图片',exact:true}).click();
  const file=await download;
  const exported=path.join(output,'focused-chart-export.png');
  await file.saveAs(exported);
  const bytes=await readFile(exported);
  assert.equal(bytes.subarray(1,4).toString(),'PNG');
  assert.ok(bytes.readUInt32BE(16)>100&&bytes.readUInt32BE(20)>100&&bytes.length>1000);
  await capture('viz-focused-desktop');
  await page.setViewportSize({width:375,height:812});
  assert.ok(await dialog.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth+1;}));
  await capture('viz-focused-mobile');
  await page.keyboard.press('Escape');
  assert.ok(await trigger.evaluate(el=>document.activeElement===el));
  pass('focused view: focus containment and return, pin/unpin, actual PNG export, mobile bounds');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'画廊',exact:true}).click();
  await page.getByRole('button',{name:`专注查看 ${title}`,exact:true}).first().click();
  const ids=await page.locator('.viz-gallery-card[id]').evaluateAll(es=>es.map(el=>el.id));
  assert.equal(ids.length,new Set(ids).size,'duplicate card/export container ids');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'列表',exact:true}).click();
  await page.getByRole('tab',{name:'历史',exact:true}).click();
  await page.getByRole('tab',{name:'可视化',exact:true}).click();
  await page.getByRole('list',{name:'图表资产列表'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'列表',exact:true}).getAttribute('aria-pressed'),'true');
  pass('gallery and inspector use distinct export containers; presentation survives navigation');
  await writeFile(path.join(output,'visualization-checks.json'),JSON.stringify({total,checks},null,2));
}
